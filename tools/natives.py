"""Recover UE3 native function names from the GNativeLookupFuncs-style tables.

The XEX keeps {const TCHAR* Name; Native Func;} pairs (8 bytes, BE) where Name is a
UTF-16BE string "int" + <Class> + "exec" + <Function>, e.g.
L"intUAIIU_ComponentexecFindActorByAIObjectName". This maps every such pair to
`Class::execFunction` at the function address.

    python3 tools/natives.py > dumps/natives.tsv          # addr  Class  execFunc
    python3 tools/natives.py --toml > config/natives.toml # names for codegen [functions]
"""
import json
import re
import struct
import sys

BASE = 0x82000000
CODE_BEGIN, CODE_END = 0x82310000, 0x83754C14
img = open("dumps/default_image.bin", "rb").read()

names: dict[int, str] = {}
for m in re.finditer(rb"\x00i\x00n\x00t\x00[A-Z]", img):
    o, e = m.start(), m.start()
    while e + 1 < len(img) and img[e : e + 2] != b"\0\0" and e - o < 400:
        e += 2
    s = img[o:e].decode("utf-16-be", "replace")
    if "exec" in s[3:]:
        names[BASE + o] = s

n = len(img) // 4
W = struct.unpack(f">{n}I", img[: n * 4])
out: dict[int, tuple[str, str]] = {}
for i in range(n - 1):
    if W[i] in names and CODE_BEGIN <= W[i + 1] < CODE_END:
        s = names[W[i]][3:]
        k = s.index("exec")
        out.setdefault(W[i + 1], (s[:k], s[k:]))

if "--toml" in sys.argv:
    known = set(json.load(open("generated/default/codegen.partition.json"))["assignments"])
    print("# Generated by tools/natives.py — UE3 native (exec*) function names from the XEX's")
    print("# native lookup tables. Regenerate rather than hand-edit.\n[functions]")
    skipped = 0
    for a, (cls, fn) in sorted(out.items()):
        if f"{a:08X}" not in known:  # only name functions codegen already knows (no boundary changes)
            skipped += 1
            continue
        print(f'0x{a:08X} = {{ name = "{cls}_{fn}" }}')
    print(f"# {len(out)} natives, {skipped} skipped (not a known function start)", file=sys.stderr)
else:
    for a, (cls, fn) in sorted(out.items()):
        print(f"{a:08X}\t{cls}\t{fn}")
    print(f"# {len(out)} natives from {len(names)} name strings", file=sys.stderr)
