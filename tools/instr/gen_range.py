#!/usr/bin/env python3
"""Writes tools/instr/scenarios/range.txt: the B-299 damage comparison for the test range (src/test_range.cpp).

For each weapon x aim point x repeat: kill the old targets, summon one stationary target, aim at its torso or head,
hold aim and fire, and mark the damage log (BOTS_RANGE_DIR) around it. The same file runs on the port and on n1; the
game needs BOTS_RANGE_DIR set (and BOTS_INSTR=1 for botsctl). Shot counts are fixed by the fire time, not by hits.

  python3 gen_range.py > scenarios/range.txt
  botsctl.py run scenarios/range.txt --out DIR --set LOG=port1
"""
import math
import os

ORIGIN = (329, -3883, 133)   # where the player stands; the chapter's open hall (52380)
YAW = 49152                  # facing -y
DISTS = [int(d) for d in os.environ.get("RANGE_DISTS", "450,900").split(",")]
WEAPONS = {"BasicRifle": 14, "HeavyPistol": 14, "SemiAutoSniper": 5, "PumpActionShotgun": 6}  # taps to kill with margin
DZ = 0                       # target height relative to the player (the pawn settles to the floor itself)
# Aim points above the pawn's root (z 122 standing). The camera sits over the right shoulder, so the shot lands
# SHOULDER uu right of and ~18 uu above the point `aim_at` is given; these offsets cancel that (calibrated against
# the damage log: aim 152 -> Spine1, aim 198 -> the head about half the time; the shot spread is +-12 uu).
AIMS = {"torso": 30, "head": 76}
SHOULDER = 18
SHOTS = os.environ.get("RANGE_SHOTS") == "1"
REPS = int(os.environ.get("RANGE_REPS", "3"))  # RANGE_DISTS / RANGE_REPS shorten a run for a quick check

fwd = (math.cos(YAW * 2 * math.pi / 65536), math.sin(YAW * 2 * math.pi / 65536))
left = (fwd[1], -fwd[0])
FLOOR_Z = 122  # root height of a pawn standing on the hall floor

print(f"""# Generated by tools/instr/gen_range.py; do not edit. Test-range damage comparison (B-299).
#   botsctl.py run scenarios/range.txt --out DIR --set LOG=port1   (the game needs BOTS_RANGE_DIR and BOTS_INSTR=1)
default CH=52380
default LOG=range
wait -t 1800 phase==front_end || phase==movie || phase==dialog || phase==menu
press_until "game.scenes~=MainMenu" START every=1000 timeout=120
dismiss
wait -t 1800 precompile.done==1
exec LoadChapter ${{CH}}
until "game.chapter==${{CH}} && phase==in_play && phase_s>=5" timeout=600
sleep 5
exec EnableCheats
exec God
sleep 1
exec range log ${{LOG}}
exec range mark chapter ${{CH}}
exec BugItGo {ORIGIN[0]} {ORIGIN[1]} {ORIGIN[2]} 0 {YAW} 0
exec Walk
sleep 2
exec range where""")
for w, taps in WEAPONS.items():
    print(f"\nexec GiveWeapon C1GameNonNative.FcWeapon_{w}\nsleep 4")
    for dist in DISTS:
        tx, ty = ORIGIN[0] + fwd[0] * dist, ORIGIN[1] + fwd[1] * dist
        ax, ay = tx + left[0] * SHOULDER, ty + left[1] * SHOULDER
        for aim, up in AIMS.items():
            for rep in range(1, REPS + 1):
                print(f"""exec Kill enemies
sleep 1
exec range spawn Kamal_Elite_SMG 1 {dist} 160 {YAW} {DZ}
exec AllAmmo
sleep 1.5
exec range mark trial {w} {aim} {dist} {rep}
macro aim_at {ax:.0f} {ay:.0f} {FLOOR_Z + up} 12000
trigger L 1.0 12000
sleep 2""")
                if SHOTS:  # RANGE_SHOTS=1: a screenshot before and during the burst (evidence for a merge request)
                    print(f"shot {w}-{aim}-{dist}-aimed")
                for i in range(taps):
                    print("macro fire 150\nsleep 0.45")
                    if SHOTS and i == 1:
                        print(f"shot {w}-{aim}-{dist}-firing")
                print("sleep 1\nexec range mark end\nmacro stop\ntrigger L 0 100\nsleep 1.5")
print("\nexec Kill enemies\nexec range mark done")
