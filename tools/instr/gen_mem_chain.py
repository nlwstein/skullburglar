#!/usr/bin/env python3
"""Writes a memory-growth scenario (B-287): one process, chapters chained with LoadChapter, no restart.

Per chapter: load, wait for play, a plain n1 `shot` after SETTLE seconds (the revisit comparison) and DWELL more seconds
of play. Chapters listed twice are revisits. With no random input the player stands where the chapter puts them, so
a shot of a revisited chapter can be compared before/after a change to what n1 keeps resident.

  gen_mem_chain.py [--chapters 11005,11040,...] [--dwell 100] [--settle 12] > scenarios/mem_chain.txt
  botsctl.py run scenarios/mem_chain.txt --out DIR     (BOTS_N1_LOG=5 for the counters; sample RSS beside it)
"""
import argparse

DEFAULT = "11005,11040,12065,21115,31165,31190,32215,32240,33250,33265,41270,42295,11040,31165"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--chapters", default=DEFAULT)
    ap.add_argument("--dwell", type=int, default=100, help="seconds of play after the settle shot")
    ap.add_argument("--settle", type=int, default=12, help="seconds into play when the shot is taken")
    a = ap.parse_args()
    out = [
        f"# Memory chain (B-287), generated by gen_mem_chain.py: {a.chapters}",
        "mark start",
        "wait -t 1800 phase==front_end || phase==movie || phase==dialog || phase==menu",
        'press_until "game.scenes~=MainMenu" START every=1000 timeout=120',
        "dismiss",
        "wait -t 1800 precompile.done==1",
        "mark precompile_done",
    ]
    seen = {}
    for k, ch in enumerate(a.chapters.split(","), 1):
        n = seen[ch] = seen.get(ch, 0) + 1
        tag = f"c{k:02d}-{ch}" + ("-rev" if n > 1 else "")
        out += [
            f"exec LoadChapter {ch}",
            f'until "game.chapter=={ch} && phase==in_play && phase_s>={a.settle}" timeout=600',
            f"mark {tag}",
            f"shot {tag}",
            f"sleep {a.dwell}",
        ]
    out.append("mark end")
    print("\n".join(out))


if __name__ == "__main__":
    main()
